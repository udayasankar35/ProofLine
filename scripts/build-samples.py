"""Builds the three fictional sample files (Word, PDF, image) used by the "Try a sample file" buttons.
Run: python3 scripts/build-samples.py   (needs python-docx, reportlab, pillow). Output: public/samples/ and lib/sample-files.ts"""
import base64, io, json, os
from docx import Document
from docx.shared import Inches
from PIL import Image, ImageDraw, ImageFont
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer

OUT = "public/samples"
os.makedirs(OUT, exist_ok=True)

def font(size, bold=False):
    for p in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
              "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"]:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()

# ---- 1. image: a social tile with a risky headline, low-contrast small print and off-palette colours
img = Image.new("RGB", (1080, 1080), "#0B2545")
d = ImageDraw.Draw(img)
d.rectangle([0, 700, 1080, 1080], fill="#FF2D95")  # hot pink block (not in the brand palette)
d.text((70, 120), "AquaPulse", font=font(96, True), fill="#FFFFFF")
d.text((70, 280), "cures fatigue!", font=font(88, True), fill="#9BD93C")
d.text((70, 420), "The #1 sports drink in India", font=font(52, True), fill="#FFFFFF")
d.text((70, 560), "Guaranteed results in 7 days", font=font(46), fill="#FFFFFF")
d.text((70, 780), "Available in 3,000 stores", font=font(40, True), fill="#FFFFFF")
d.text((70, 980), "Terms apply. See website for details.", font=font(20), fill="#F3A6CF")  # small, low contrast on pink
img.save(f"{OUT}/aquapulse-social-tile.png", optimize=True)

# ---- 2. Word press release with a picture that has no alt text
buf = io.BytesIO()
Image.new("RGB", (600, 300), "#1B9AAA").save(buf, "PNG")
buf.seek(0)
doc = Document()
doc.add_heading("AquaPulse launches Summer Splash", level=1)
doc.add_paragraph("FOR IMMEDIATE RELEASE")
doc.add_paragraph("AquaPulse, the best-selling sports drink in India, today announced its Summer Splash campaign. Our bottles are made with 40% recycled PET, and the drink is sold in more than 2,000 stores across 14 Indian states.")
doc.add_picture(buf, width=Inches(4.5))
doc.add_paragraph("AquaPulse is the cheap, tasty way to recover after a workout. Athletes report instant relief from fatigue and guaranteed results within 7 days. Join the 12 athletes we sponsor this season.")
doc.add_paragraph("Each 500 ml bottle has 90 calories and no added caffeine.")
doc.save(f"{OUT}/aquapulse-press-release.docx")

# ---- 3. PDF flyer (has a text layer)
styles = getSampleStyleSheet()
pdf = SimpleDocTemplate(f"{OUT}/aquapulse-flyer.pdf", pagesize=A4, title="AquaPulse summer flyer")
pdf.build([
    Paragraph("AquaPulse Summer Offer", styles["Title"]),
    Paragraph("Beat the heat with AquaPulse, the energy drink that is clinically proven to boost immunity.", styles["BodyText"]),
    Spacer(1, 10),
    Paragraph("Sold in more than 3,000 stores across 20 states. Free delivery on orders above Rs 499 on our website. Rated number one by athletes.", styles["BodyText"]),
    Spacer(1, 10),
    Paragraph("Each 500 ml bottle has 90 calories and no added caffeine. AquaPulse replaces electrolytes lost through sweat with sodium, potassium and magnesium.", styles["BodyText"]),
])

# ---- python-free loader module for the app
files = [
    ("tile", "Social tile (image)", "aquapulse-social-tile.png", "Summer social tile", "Instagram", "image/png"),
    ("release", "Press release (Word)", "aquapulse-press-release.docx", "Summer Splash press release", "Press note", "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
    ("flyer", "Flyer (PDF)", "aquapulse-flyer.pdf", "Summer offer flyer", "Website", "application/pdf"),
]
lines = ["// Generated by scripts/build-samples.py. Fictional AquaPulse sample files, embedded so they work on any host.", "export interface SampleFile { id: string; label: string; name: string; title: string; channel: string; mime: string; base64: string; }", "export const SAMPLE_FILES: SampleFile[] = ["]
for id_, label, name, title, ch, mime in files:
    b = base64.b64encode(open(f"{OUT}/{name}", "rb").read()).decode()
    lines.append(f"  {{ id: {json.dumps(id_)}, label: {json.dumps(label)}, name: {json.dumps(name)}, title: {json.dumps(title)}, channel: {json.dumps(ch)}, mime: {json.dumps(mime)}, base64: {json.dumps(b)} }},")
lines.append("];")
open("lib/sample-files.ts", "w").write("\n".join(lines) + "\n")
print({n: os.path.getsize(f"{OUT}/{n}") for _, _, n, *_ in files})
